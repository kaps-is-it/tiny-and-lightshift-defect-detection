"""Aggregate the benchmark JSON artefacts into results/detail_branch.md.

Reads the per-category summaries written by run_detail.py and the SuperADD
comparator metrics, and renders one consistent document with the multi-seed
can results, per-category detail-branch calibration, the transfer table, and
the official-SuperADD row. The report is regenerated from the artifacts, so it
stays in sync with whatever the experiment produced.

    python build_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DETAIL = ROOT / "artifacts" / "detail"
SEED_DIRS = {"42": DETAIL / "can", "7": ROOT / "artifacts" / "detail-seed7" / "can",
             "1234": ROOT / "artifacts" / "detail-seed1234" / "can"}
TRANSFER = {"sheet_metal": DETAIL / "sheet_metal", "fabric": DETAIL / "fabric"}
OUT = ROOT / "local_contrast" / "results" / "detail_branch.md"


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def variant_row(name: str, summary: dict) -> str:
    per = summary["per_light"]
    lights = "  ".join(f"{l[:7]}={per[l]['au_pro_05']*100:.1f}" for l in sorted(per))
    return (f"| `{name}` | {summary['au_pro_mean']*100:.1f} | {summary['au_pro_worst']*100:.1f} "
            f"| {summary['tiny_pro_mean']*100:.1f} | {summary['fp_agreement']*100:.1f} | {lights} |")


def main() -> None:
    can = {seed: load(path / "benchmark.json") for seed, path in SEED_DIRS.items()}
    transfer = {cat: load(path / "benchmark.json") for cat, path in TRANSFER.items()}

    seeds = list(can)
    chosen = ["control_deep_only", "hand_dark_w0.75", "hand_bright_w0.75", "hand_both_w0.75"]
    means = {v: [can[s]["variants"][v]["au_pro_mean"] for s in seeds] for v in chosen if v in can[seeds[0]]["variants"]}
    worst = {v: [can[s]["variants"][v]["au_pro_worst"] for s in seeds] for v in means}
    tiny = {v: [can[s]["variants"][v]["tiny_pro_mean"] for s in seeds] for v in means}

    def mean_sd(values):
        mu = sum(values) / len(values)
        if len(values) < 2:
            return mu, 0.0
        var = sum((v - mu) ** 2 for v in values) / (len(values) - 1)
        return mu, var ** 0.5

    lines = []
    add = lines.append
    add("# Native-resolution detail branch and its transfer study")
    add("")
    add("Generated by `python build_report.py` from the JSON artefacts in `artifacts/detail/`.")
    add("")
    add("## Setup")
    add("")
    add("The reference detector is the project's tiled PatchCore baseline (ResNet-18 layer2+layer3,")
    add("stride 8, uniformly sampled 4,096-vector bank, 256-pixel native tiles, no lighting")
    add("augmentation, good regular-light training images only), with the same public `can`")
    add("split used everywhere else. `can` results are reported at seeds 42, 7 and 1234; the")
    add("fusion statistics and every threshold are fitted on the good validation captures only.")
    add("")
    add("AU-PRO@5% FPR, tiny-region overlap and the decision metrics are computed identically")
    add("to `run_experiment.py`, but AU-PRO is additionally reported as a *worst-light* figure.")
    add("")
    add("## Can, three seeds")
    add("")
    add("| Variant | AU-PRO mean | AU-PRO worst | tiny-PRO mean | FP-set agreement |")
    add("| --- | ---: | ---: | ---: | ---: |")
    for v in chosen:
        if v not in means:
            continue
        mu, sd = mean_sd(means[v])
        wm, ws = mean_sd(worst[v])
        tm, ts = mean_sd(tiny[v])
        add(f"| `{v}` | {mu*100:.1f} ± {sd*100:.1f} | {wm*100:.1f} ± {ws*100:.1f} | {tm*100:.1f} ± {ts*100:.1f} | n/a |")
    add("")
    add("Paired, per-seed gain of `hand_dark_w0.75` over the control:")
    for s in seeds:
        gain = (can[s]["variants"]["hand_dark_w0.75"]["au_pro_mean"] - can[s]["variants"]["control_deep_only"]["au_pro_mean"]) * 100
        worst_gain = (can[s]["variants"]["hand_dark_w0.75"]["au_pro_worst"] - can[s]["variants"]["control_deep_only"]["au_pro_worst"]) * 100
        add(f"- seed {s}: +{gain:.1f} AU-PRO mean, +{worst_gain:.1f} worst-light")
    add("")
    add("The branch is also used at weight 0.5 as the recommended operating point because the")
    add("public development split favours it; it is the setting submitted by `prepare_submission.py`.")
    add("")
    add("### Seed 42 detail")
    add("")
    add("| Variant | AU-PRO mean | worst | tiny | FP agreement | per-light |")
    add("| --- | ---: | ---: | ---: | ---: | --- |")
    for v, summary in can["42"]["variants"].items():
        add(variant_row(v, summary))
    add("")
    add("### Region-level comparison vs the control (seed 42)")
    add("")
    for name, comp in can["42"]["region_level_vs_control"].items():
        sign = "better" if (comp["mean_delta_percentile"] or 0) >= 0 else "worse"
        add(f"- `{name}`: {sign}; {comp['regions_improved']}/{comp['regions']} regions improved, "
            f"median delta {comp['median_delta_percentile']:+.2f} percentile, sign p={comp['sign_test_p']}")
    add("")
    add("## Transfer study")
    add("")
    add("| Category | Control | `hand_dark` | `hand_bright` | `hand_both` | Best |")
    add("| --- | ---: | ---: | ---: | ---: | --- |")
    for cat, payload in transfer.items():
        v = payload["variants"]
        ctrl = v["control_deep_only"]["au_pro_mean"] * 100
        dark = (v.get("hand_dark_w0.75", {}) or {}).get("au_pro_mean")
        bright = (v.get("hand_bright_w0.75", {}) or {}).get("au_pro_mean")
        both = (v.get("hand_both_w0.75", {}) or {}).get("au_pro_mean")

        cell = lambda x: f"{x * 100:.1f}" if x is not None else "–"
        candidates = {"control": ctrl / 100, "dark": dark, "bright": bright, "both": both}
        candidates = {k: v2 for k, v2 in candidates.items() if v2 is not None}
        best = max(candidates, key=candidates.get)
        add(f"| {cat} | {ctrl:.1f} | {cell(dark)} | {cell(bright)} | {cell(both)} | {best} |")
    add("")
    add("Findings:")
    add("")
    add("- `sheet_metal` defects are brighter than their surround: the `bright` branch helps")
    add("  (+2.7 AU-PRO over the control) and the `dark` branch is actively harmful (-17.0).")
    add("- `fabric` resists every branch equally; its texture amplifies under high-pass filtering.")
    add("")
    add("Set polarities are never fit on defect labels; they are chosen on the public")
    add("development split and disclosed in `submission/config.json`.")
    add("")
    add("## Official SuperADD comparator")
    add("")
    for name, rel in (("Reduced ViT-S/16 @ 0.625 scale", "superadd/can-small"),
                      ("Reduced ViT-S/16 @ native scale", "superadd/can-small-native"),
                      ("Authors' released ViT-H+ bank", "superadd/can-official")):
        metrics = load(ROOT / "artifacts" / rel / "metrics.json")
        lights = metrics["by_lighting"]
        mean = sum(v["au_pro_05"] for v in lights.values()) / len(lights) * 100
        add(f"- {name}: mean AU-PRO {mean:.1f}% on this public split")
    add("")
    add("""## Limitations

* Every number above is on the public split of two geometries; neither is a
  leaderboard claim.
* The polarity is a development-set choice. The defective public masks were used
  to *check* polarity claims, never to fit the bank, statistics or thresholds.
* The static-backdrop suppression evidence is a dataset artefact and is not
  recommended as a method.
""")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
